package core

import (
	"encoding/json"
	"net/http/httptest"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func postSaveRequest(s *Service, path, body string) *httptest.ResponseRecorder {
	r := httptest.NewRequest("POST", path, strings.NewReader(body))
	r.Header.Set("X-Tami-Client", "desktop")
	w := httptest.NewRecorder()
	s.Handler(nil).ServeHTTP(w, r)
	return w
}

func TestGeneratedConfigSaveUsesCoreValueAndSafePublish(t *testing.T) {
	s, _ := testService(t)
	dest := filepath.Join(t.TempDir(), "chosen-config.json")
	var suggested string
	s.PickSave = func(name string) (string, error) {
		suggested = name
		return dest, nil
	}

	w := postSaveRequest(s, "/api/config/save", "{invalid arbitrary payload")
	if w.Code != 200 {
		t.Fatalf("status=%d body=%s", w.Code, w.Body.String())
	}
	if suggested != "tamias-config.json" {
		t.Fatalf("suggested name=%q", suggested)
	}
	var response struct {
		Saved bool   `json:"saved"`
		Path  string `json:"path"`
		Name  string `json:"name"`
	}
	if err := json.Unmarshal(w.Body.Bytes(), &response); err != nil {
		t.Fatal(err)
	}
	if !response.Saved || response.Path != dest || response.Name != filepath.Base(dest) {
		t.Fatalf("response=%+v", response)
	}
	data, err := os.ReadFile(dest)
	if err != nil {
		t.Fatal(err)
	}
	var exported ConfigurationExport
	if err = json.Unmarshal(data, &exported); err != nil {
		t.Fatal(err)
	}
	if exported.Version != 1 {
		t.Fatalf("saved payload was not generated by Core: version=%d", exported.Version)
	}

	w = postSaveRequest(s, "/api/config/save", "")
	if w.Code != 400 {
		t.Fatalf("existing destination status=%d body=%s", w.Code, w.Body.String())
	}
	dataAfter, err := os.ReadFile(dest)
	if err != nil || string(dataAfter) != string(data) {
		t.Fatalf("existing file was changed: err=%v", err)
	}
}

