func TestGeneratedSaveCancellationIsAnError(t *testing.T) {
	s, _ := testService(t)
	s.PickSave = func(string) (string, error) { return "", nil }
	w := postSaveRequest(s, "/api/diagnostics/save", "")
	if w.Code != 400 || !strings.Contains(w.Body.String(), "已取消保存") {
		t.Fatalf("status=%d body=%s", w.Code, w.Body.String())
	}
}
